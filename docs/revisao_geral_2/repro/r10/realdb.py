import sqlite3,sys
c=sqlite3.connect('file:'+sys.argv[1]+'?mode=ro',uri=True)
q=lambda s: c.execute(s).fetchall()
print('players', q('select count(*) from players'))
print('fide_id preenchido', q("select count(*) from players where trim(coalesce(fide_id,''))<>''"))
print('fide_id e intl=0 e rating>0', q("select count(*) from players where trim(coalesce(fide_id,''))<>'' and coalesce(international_rating,0)=0 and coalesce(rating,0)>0"))
print('fide_id e intl>0', q("select count(*) from players where trim(coalesce(fide_id,''))<>'' and coalesce(international_rating,0)>0"))
print('sem fide_id e rating>0', q("select count(*) from players where trim(coalesce(fide_id,''))='' and coalesce(rating,0)>0"))
print('intl>0 e rating<>intl', q("select count(*) from players where coalesce(international_rating,0)>0 and rating<>international_rating"))
print('por torneio (fide_id, intl=0, rating>0)', q("select tournament_id,count(*) from players where trim(coalesce(fide_id,''))<>'' and coalesce(international_rating,0)=0 and coalesce(rating,0)>0 group by 1 limit 10"))
print('members', q('select count(*) from members'), 'players com member_id', q('select count(*) from players where member_id is not null'))
print('categories', q("select category, count(*) from players group by 1 order by 2 desc limit 8"))
print('tcats', q("select count(*) from tournament_categories"))
